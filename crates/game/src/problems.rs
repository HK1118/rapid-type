use crate::question::Question;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Difficulty {
    Easy,
    #[default]
    Normal,
    Hard,
}

impl Difficulty {
    pub fn label(&self) -> &'static str {
        match self {
            Difficulty::Easy => "イージー (3-6文字)",
            Difficulty::Normal => "ノーマル (7-11文字)",
            Difficulty::Hard => "ハード (12文字以上)",
        }
    }

    pub fn pool(&self) -> Vec<Question> {
        match self {
            Difficulty::Easy => easy_pool(),
            Difficulty::Normal => normal_pool(),
            Difficulty::Hard => hard_pool(),
        }
    }
}

